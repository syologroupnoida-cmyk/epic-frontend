import test from 'node:test';
import assert from 'node:assert/strict';
import axios from 'axios';
import { updateEcommerceCategory, deleteEcommerceCategory, fetchEcommerceCategory, fetchEcommerceCategories } from '../src/util/ecommerceCategories.mjs';
import { updateEcommerceSubcategory, fetchEcommerceSubcategories } from '../src/util/ecommerceSubcategories.mjs';
import { ecommerceProductUpdatePayload, updateEcommerceProduct, archiveEcommerceProduct, fetchEcommerceProduct } from '../src/util/ecommerceProducts.mjs';
const category = { name: 'Updated Bridal Wear', description: 'Updated description', sortOrder: 0 };
const subcategory = { categoryId: 'category & one', name: 'Updated Lehenga', specificationTemplate: { fields: [{ key: 'blouseIncluded', label: 'Blouse Included', type: 'BOOLEAN', required: false }] } };
const product = { categoryId: 'category & one', subcategoryId: 'subcategory & one', title: 'Updated Bridal Lehenga', description: 'Updated silk product', brandName: 'Epic', gstPercentage: '5', specifications: { fabric: 'Silk', blouseIncluded: false }, optionDefinitions: [] };
test('catalog update helpers encode IDs, use PATCH and DELETE, and exclude unrelated fields', async () => {
  const calls = []; const response = { data: { success: true, data: {} } };
  const api = { patch: async (...args) => { calls.push(['PATCH', ...args]); return response; }, delete: async (...args) => { calls.push(['DELETE', ...args]); return response; }, post: async (...args) => { calls.push(['POST', ...args]); return response; } };
  await updateEcommerceCategory(api, 'category & one', { ...category, ignored: true });
  await updateEcommerceSubcategory(api, 'subcategory & one', { ...subcategory, ignored: true });
  await deleteEcommerceCategory(api, 'category & one');
  await updateEcommerceProduct(api, 'product & one', { ...product, images: ['ignored'], variants: ['ignored'], status: 'ignored' });
  await archiveEcommerceProduct(api, 'product & one');
  assert.equal(calls[0][0], 'PATCH'); assert.equal(calls[0][1], '/admin/ecommerce/categories/category%20%26%20one'); assert.deepEqual(calls[0][2], category);
  assert.equal(calls[1][1], '/admin/ecommerce/subcategories/subcategory%20%26%20one'); assert.deepEqual(calls[1][2], subcategory);
  assert.equal(calls[2][0], 'DELETE'); assert.equal(calls[2][1], calls[0][1]);
  assert.equal(calls[3][1], '/admin/ecommerce/products/product%20%26%20one'); assert.deepEqual(calls[3][2], { ...product, gstPercentage: 5 });
  assert.equal(calls[4][0], 'POST'); assert.equal(calls[4][1], '/admin/ecommerce/products/product%20%26%20one/archive'); assert.deepEqual(calls[4][2], {});
  await assert.rejects(updateEcommerceCategory(api, '', category), /ID/);
  await assert.rejects(deleteEcommerceCategory(api, ''), /ID/);
  assert.throws(() => ecommerceProductUpdatePayload({ ...product, gstPercentage: 101 }));
  assert.throws(() => ecommerceProductUpdatePayload({ ...product, optionDefinitions: [{ name: '', values: [] }] }));
  assert.equal(calls.length, 5);
});
const categoryBase = process.env.ECOMMERCE_CATEGORIES_SIMULATION_URL;
const productBase = process.env.ECOMMERCE_PRODUCTS_SIMULATION_URL;
const clients = () => ({ categories: axios.create({ baseURL: categoryBase, proxy: false, headers: { Authorization: 'Bearer ecommerce-category-test-token' } }), products: axios.create({ baseURL: productBase, proxy: false, headers: { Authorization: 'Bearer ecommerce-product-test-token' } }) });
async function reset(api, baseURL) { await api.post(`${baseURL.replace(/\/api\/v1$/, '')}/__reset`, {}); }
test('HTTP category and subcategory updates persist; only empty categories can be deleted', { skip: !categoryBase || !productBase }, async () => {
  const api = clients(); await reset(api.categories, categoryBase); await reset(api.products, productBase);
  await updateEcommerceCategory(api.categories, 'category & one', category);
  assert.equal((await fetchEcommerceCategory(api.categories, 'category & one')).name, category.name);
  await updateEcommerceSubcategory(api.categories, 'subcategory & one', subcategory);
  const updated = (await fetchEcommerceSubcategories(api.categories)).items.find(row => row.ecommerceSubcategoryId === 'subcategory & one');
  assert.deepEqual(updated.specificationTemplate, subcategory.specificationTemplate);
  await assert.rejects(deleteEcommerceCategory(api.categories, 'category & one'), error => error.response.status === 409);
  const before = await fetchEcommerceCategories(api.categories);
  await deleteEcommerceCategory(api.categories, 'category-3');
  assert.equal((await fetchEcommerceCategories(api.categories)).total, before.total - 1);
  await assert.rejects(fetchEcommerceCategory(api.categories, 'category-3'), error => error.response.status === 404);
  api.categories.defaults.headers['x-test-catalog'] = 'after-write';
  await assert.rejects(updateEcommerceCategory(api.categories, 'category & one', { ...category, name: 'Saved despite response failure' }), error => error.response.status === 503);
  delete api.categories.defaults.headers['x-test-catalog'];
  assert.equal((await fetchEcommerceCategory(api.categories, 'category & one')).name, 'Saved despite response failure');
});
test('HTTP product PATCH preserves media and variants; archive uses POST and persists status', { skip: !productBase }, async () => {
  const api = clients().products; await reset(api, productBase);
  const original = await fetchEcommerceProduct(api, 'product-1');
  await updateEcommerceProduct(api, 'product-1', product);
  let updated = await fetchEcommerceProduct(api, 'product-1');
  assert.equal(updated.title, product.title); assert.deepEqual(updated.specifications, product.specifications);
  assert.deepEqual(updated.variants, original.variants); assert.deepEqual(updated.images, original.images);
  api.defaults.headers['x-test-catalog'] = 'unavailable';
  await assert.rejects(archiveEcommerceProduct(api, 'product-1'), error => error.response.status === 503);
  delete api.defaults.headers['x-test-catalog'];
  assert.equal((await fetchEcommerceProduct(api, 'product-1')).status, 'DRAFT');
  await archiveEcommerceProduct(api, 'product-1'); updated = await fetchEcommerceProduct(api, 'product-1'); assert.equal(updated.status, 'ARCHIVED');
});
